    try {
        $colStmt = $pdo->query('SELECT column_name AS "Field", data_type AS "Type", is_nullable AS "Null", column_default AS "Default" FROM information_schema.columns WHERE table_schema=current_schema() AND table_name=\'alarm_systems\' ORDER BY ordinal_position');
        foreach ($colStmt->fetchAll() as $c) $existingCols[] = $c['Field'];
    } catch (PDOException $e) {}

    foreach ([
        'sound_url'              => "VARCHAR(500) NULL",
        'sound_volume'           => "INT DEFAULT 80",
        'siren_duration'         => "INT DEFAULT 180",
        'trigger_delay_seconds'  => "INT DEFAULT 120",
        'auto_sound_on_incident' => "SMALLINT DEFAULT 1",
    ] as $col => $def) {
        if (!in_array($col, $existingCols)) {
            try { $pdo->exec("ALTER TABLE alarm_systems ADD COLUMN $col $def"); } catch (PDOException $e) {}
        }
    }
} catch (PDOException $e) {
    error_log('[WS-SUP-AL] DDL: ' . $e->getMessage());
