        CREATE TABLE IF NOT EXISTS alarm_triggers (
            id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            alarm_id INTEGER NULL,
            alert_id INTEGER NULL,
            incident_id INTEGER NULL,
            zone_id INTEGER NOT NULL,
            triggered_by TEXT DEFAULT \'manual\',
            trigger_reason VARCHAR(255) NULL,
            triggered_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
            stopped_at TIMESTAMP NULL,
            duration_seconds INT NULL,
            was_acknowledged SMALLINT DEFAULT 0,
            acknowledged_by INTEGER NULL,
            acknowledged_at TIMESTAMP NULL
        )
    ');

