CREATE FUNCTION GetNearbyIncidents(p_lat DECIMAL(10,8),
    p_lng DECIMAL(11,8),
    p_radius integer,
    p_limit integer) RETURNS TABLE (id integer, reporter_id integer, reporter_type text, zone_id integer, category text, severity text, description text, location_lat numeric(10,8), location_lng numeric(11,8), location_geojson point, media_urls jsonb, status text, reported_at timestamp without time zone, acknowledged_by integer, acknowledged_at timestamp without time zone, resolved_at timestamp without time zone, is_simulated smallint, distance double precision) LANGUAGE sql STABLE AS $$
SELECT * FROM (SELECT *,
           (6371 * ACOS(COS(RADIANS(p_lat)) * COS(RADIANS(location_lat)) *
            COS(RADIANS(location_lng) - RADIANS(p_lng)) +
            SIN(RADIANS(p_lat)) * SIN(RADIANS(location_lat)))) AS distance
    FROM incidents
    WHERE status NOT IN ('resolved','closed')
    ) AS nearby WHERE distance < p_radius 
    ORDER BY distance ASC, CASE severity WHEN 'critical' THEN 1 WHEN 'high' THEN 2 WHEN 'medium' THEN 3 WHEN 'low' THEN 4 ELSE 0 END
    LIMIT p_limit;
$$;
