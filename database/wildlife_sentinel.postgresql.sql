-- Wildlife Sentinel PostgreSQL schema. Run only in an empty application schema.
BEGIN;
-- Refuse an existing application schema. All changes roll back on any error.
DO $$ BEGIN
    IF EXISTS (SELECT 1 FROM information_schema.tables WHERE table_schema = current_schema()) THEN
        RAISE EXCEPTION 'Schema is not empty. No existing tables will be overwritten.';
    END IF;
END $$;
CREATE FUNCTION ws_point_from_wkt(value text) RETURNS point LANGUAGE sql IMMUTABLE STRICT AS $$ SELECT replace(regexp_replace(value, '^POINT\((.*)\)$', '\1', 'i'), ' ', ',')::point $$;
CREATE FUNCTION ws_point_to_wkt(value point) RETURNS text LANGUAGE sql IMMUTABLE STRICT AS $$ SELECT 'POINT(' || value[0] || ' ' || value[1] || ')' $$;
CREATE FUNCTION ws_touch_updated_at() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN NEW.updated_at := CURRENT_TIMESTAMP; RETURN NEW; END $$;
