CREATE FUNCTION ws_assignment_insert() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 IF NEW.status = 'accepted' THEN UPDATE ranger_availability SET is_available=0, current_incident_id=NEW.incident_id WHERE ranger_id=NEW.ranger_id; END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER update_ranger_availability_on_assignment AFTER INSERT ON incident_assignments FOR EACH ROW EXECUTE FUNCTION ws_assignment_insert();
CREATE FUNCTION ws_incident_resolved() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 IF NEW.status='resolved' AND OLD.status<>'resolved' THEN UPDATE ranger_availability SET is_available=1,current_incident_id=NULL WHERE current_incident_id=NEW.id; END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER update_ranger_availability_on_resolution AFTER UPDATE ON incidents FOR EACH ROW EXECUTE FUNCTION ws_incident_resolved();
CREATE FUNCTION ws_incident_point() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 IF TG_OP='INSERT' THEN
   IF NEW.location_geojson IS NULL
      OR (NEW.location_geojson[0] = 0 AND NEW.location_geojson[1] = 0)
   THEN
      NEW.location_geojson := point(NEW.location_lng, NEW.location_lat);
   END IF;
 ELSIF NEW.location_lat IS DISTINCT FROM OLD.location_lat OR NEW.location_lng IS DISTINCT FROM OLD.location_lng THEN
   NEW.location_geojson := point(NEW.location_lng, NEW.location_lat);
 END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER set_incident_location_geojson BEFORE INSERT OR UPDATE ON incidents FOR EACH ROW EXECUTE FUNCTION ws_incident_point();
