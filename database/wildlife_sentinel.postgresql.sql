CREATE FUNCTION GetZoneAIAnomalies(p_zone_id integer, p_limit integer) RETURNS TABLE (id integer, zone_id integer, type text, severity text, description text, confidence numeric(4,3), location_lat numeric(10,8), location_lng numeric(11,8), radius_meters integer, ranger_id integer, scout_id integer, is_acknowledged smallint, acknowledged_by integer, acknowledged_at timestamp without time zone, detected_at timestamp without time zone, subject_name character varying(255), subject_role text) LANGUAGE sql STABLE AS $$
SELECT a.*, u.full_name AS subject_name, u.role AS subject_role
    FROM ai_anomalies a
    LEFT JOIN users u ON (a.ranger_id = u.id OR a.scout_id = u.id)
    WHERE a.zone_id = p_zone_id
      AND a.detected_at >= (NOW() - (24) * INTERVAL '1 hour')
    ORDER BY a.detected_at DESC
    LIMIT p_limit;
$$;

